def normalize_keyword(value: str) -> str:
    return re.sub(r"\s+", " ", value.casefold()).strip()


def keyword_coverage(
    document: TailoredCvDocument,
    matched_keywords: list[str],
) -> float:
    if not matched_keywords:
        return 1.0

    searchable_text = normalize_keyword(
        " ".join(
            [
                document.professional_summary,
                *document.skills,
                document_evidence_text(document),
            ]
        )
    )
    covered = sum(
        1
        for keyword in matched_keywords
        if normalize_keyword(keyword) in searchable_text
    )
    return covered / len(matched_keywords)


def keyword_placement_score(
    document: TailoredCvDocument,
    matched_keywords: list[str],
) -> float:
    """Measure whether supported keywords appear across useful ATS sections."""

    if not matched_keywords:
        return 1.0

    sections = [
        normalize_keyword(
            " ".join(
                part
                for part in [document.headline, document.professional_summary]
                if part
            )
        ),
        normalize_keyword(" ".join(document.skills)),
        normalize_keyword(document_evidence_text(document)),
    ]
    placements = sum(
        1
        for keyword in matched_keywords
        for section in sections
        if normalize_keyword(keyword) in section
    )
    return placements / (len(matched_keywords) * len(sections))


def same_keyword_classification(
    first: TailoringResult,
    candidate: TailoringResult,
) -> bool:
    return {
        normalize_keyword(keyword) for keyword in first.matched_keywords
    } == {
        normalize_keyword(keyword) for keyword in candidate.matched_keywords
    } and {
        normalize_keyword(keyword) for keyword in first.missing_keywords
    } == {
        normalize_keyword(keyword) for keyword in candidate.missing_keywords
    }


def prioritize_skills(skills: list[str], job_description: str | None) -> list[str]:
    """Move existing job-relevant skills first without changing their contents."""

    if not job_description:
        return list(skills)

    normalized_job = normalize_keyword(job_description)
    indexed_skills = list(enumerate(skills))
    indexed_skills.sort(
        key=lambda item: (
            0 if normalize_keyword(item[1]) in normalized_job else 1,
            item[0],
        )
    )
    return [skill for _, skill in indexed_skills]


def validate_and_merge_tailoring(
    master_cv: MasterCv,
    tailoring: TailoringResult,
    job_description: str | None = None,
) -> TailoredCvDocument:
    """
    Enforce a one-to-one mapping between original and rewritten work history.

    Immutable identifying data is copied only from the Master CV, never from the
    model response.
    """

    expected_experience_indices = set(range(len(master_cv.work_experience)))
    returned_experience_indices = [
        rewrite.experience_index for rewrite in tailoring.experience_rewrites
    ]

    if (
        len(returned_experience_indices) != len(expected_experience_indices)
        or set(returned_experience_indices) != expected_experience_indices
    ):
        raise AiOutputError(
            "AI output did not map every source work experience exactly once."
        )

    rewrites_by_experience = {
        rewrite.experience_index: rewrite
        for rewrite in tailoring.experience_rewrites
    }
    tailored_experiences: list[TailoredWorkExperience] = []

    for experience_index, source_experience in enumerate(
        master_cv.work_experience
    ):
        rewrite = rewrites_by_experience[experience_index]
        expected_bullet_indices = set(range(len(source_experience.bullet_points)))
        returned_bullet_indices = [
            bullet.source_bullet_index for bullet in rewrite.bullet_points
        ]

        if (
            len(returned_bullet_indices) != len(expected_bullet_indices)
            or set(returned_bullet_indices) != expected_bullet_indices
        ):
            raise AiOutputError(
                "AI output did not map every source bullet exactly once for "
                f"experience index {experience_index}."
            )

        bullets_by_index = {
            bullet.source_bullet_index: bullet.text
            for bullet in rewrite.bullet_points
        }
        tailored_experiences.append(
            TailoredWorkExperience(
                company=source_experience.company,
                job_title=source_experience.job_title,
                start_date=source_experience.start_date,
                end_date=source_experience.end_date,
                location=source_experience.location,
                bullet_points=[
                    bullets_by_index[index]
                    for index in range(len(source_experience.bullet_points))
                ],
            )
        )

    expected_project_indices = set(range(len(master_cv.projects)))
    returned_project_indices = [
        rewrite.project_index for rewrite in tailoring.project_rewrites
    ]
    if (
        len(returned_project_indices) != len(expected_project_indices)
        or set(returned_project_indices) != expected_project_indices
    ):
        raise AiOutputError("AI output did not map every source project exactly once.")

    project_rewrites = {
        rewrite.project_index: rewrite for rewrite in tailoring.project_rewrites
    }
    tailored_projects: list[TailoredProject] = []
    for project_index, source_project in enumerate(master_cv.projects):
        rewrite = project_rewrites[project_index]
        expected_bullet_indices = set(range(len(source_project.bullet_points)))
        returned_bullet_indices = [
            bullet.source_bullet_index for bullet in rewrite.bullet_points
        ]
        if (
            len(returned_bullet_indices) != len(expected_bullet_indices)
            or set(returned_bullet_indices) != expected_bullet_indices
        ):
            raise AiOutputError(
                "AI output did not map every source bullet exactly once for "
                f"project index {project_index}."
            )
        bullets_by_index = {
            bullet.source_bullet_index: bullet.text
            for bullet in rewrite.bullet_points
        }
        tailored_projects.append(
            TailoredProject(
                name=source_project.name,
                role=source_project.role,
                start_date=source_project.start_date,
                end_date=source_project.end_date,
                url=source_project.url,
                technologies=list(source_project.technologies),
                bullet_points=[
                    bullets_by_index[index]
                    for index in range(len(source_project.bullet_points))
                ],
            )
        )

    return TailoredCvDocument(
        full_name=master_cv.full_name,
        headline=master_cv.headline,
        professional_summary=tailoring.professional_summary,
        email=master_cv.email,
        phone=master_cv.phone,
        location=master_cv.location,
        linkedin=master_cv.linkedin,
        website=master_cv.website,
        skills=prioritize_skills(master_cv.skills, job_description),
        work_experience=tailored_experiences,
        projects=tailored_projects,
        education=master_cv.education,
        certifications=master_cv.certifications,
        courses=master_cv.courses,
        languages=master_cv.languages,
    )


async def tailor_cv_with_openai(
    request: GenerateTailoredCvRequest,
    client: AsyncOpenAI,
    settings: Settings,
) -> TailoringResult:
    """Generate one grounded draft and optionally refine low-scoring wording."""

    def validate_and_score(candidate: TailoringResult) -> tuple[TailoringResult, TailoredCvDocument]:
        if request.keyword_baseline is not None:
            matched = list(request.keyword_baseline.matched_keywords)
            missing = list(request.keyword_baseline.missing_keywords)
        else:
            matched, missing = reconcile_keyword_evidence(
                request.master_cv,
                candidate.matched_keywords,
                candidate.missing_keywords,
                candidate.keyword_evidence,
            )
        grounded = candidate.model_copy(
            update={
                "matched_keywords": matched,
                "missing_keywords": missing,
            }
        )
        document = validate_and_merge_tailoring(
            request.master_cv,
            grounded,
            request.job_description,
        )
        scored = grounded.model_copy(
            update={
                "ats_match_score": calculate_ats_score(
                    document,
                    matched,
                    missing,
                )
            }
        )
        return scored, document

    def protect_original_score(candidate: TailoringResult) -> TailoringResult:
        """Never return a tailored document that scores below its source CV."""

        original_score = calculate_ats_score(
            source_cv_document(request.master_cv),
            candidate.matched_keywords,
            candidate.missing_keywords,
        )
        if candidate.ats_match_score >= original_score:
            return candidate

        return TailoringResult(
            professional_summary=request.master_cv.professional_summary,
            experience_rewrites=[
                ExperienceRewrite(
                    experience_index=experience_index,
                    bullet_points=[
                        TailoredBullet(source_bullet_index=index, text=bullet)
                        for index, bullet in enumerate(experience.bullet_points)
                    ],
                )
                for experience_index, experience in enumerate(
                    request.master_cv.work_experience
                )
            ],
            project_rewrites=[
                ProjectRewrite(
                    project_index=project_index,
                    bullet_points=[
                        TailoredBullet(source_bullet_index=index, text=bullet)
                        for index, bullet in enumerate(project.bullet_points)
                    ],
                )
                for project_index, project in enumerate(request.master_cv.projects)
            ],
            matched_keywords=candidate.matched_keywords,
            missing_keywords=candidate.missing_keywords,
            keyword_evidence=candidate.keyword_evidence,
            ats_match_score=original_score,
        )

    async def request_tailoring(prompt: str, temperature: float) -> TailoringResult:
        completion = await client.chat.completions.create(
            model=settings.openai_model,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            response_format={"type": "json_object"},
            temperature=temperature,
            max_tokens=settings.openai_max_output_tokens,
        )

        if not completion.choices:
            raise AiOutputError("OpenAI returned no completion choices.")

        choice = completion.choices[0]
        refusal = getattr(choice.message, "refusal", None)
        if refusal:
            raise AiOutputError("OpenAI refused the tailoring request.")

        if choice.finish_reason != "stop":
            raise AiOutputError(
                f"OpenAI completion ended with finish reason '{choice.finish_reason}'."
            )

        content = choice.message.content
        if not content:
            raise AiOutputError("OpenAI returned an empty tailoring result.")

        try:
            return TailoringResult.model_validate_json(content)
        except ValidationError as exc:
            raise AiOutputError(
                "OpenAI returned JSON that does not match the tailoring contract."
            ) from exc

    initial, initial_document = validate_and_score(
        await request_tailoring(build_tailoring_prompt(request), 0.1)
    )

    threshold = settings.openai_ats_refinement_threshold
    if (
        threshold == 0
        or initial.ats_match_score >= threshold
        or not initial.matched_keywords
    ):
        return protect_original_score(initial)

    try:
        candidate, candidate_document = validate_and_score(
            await request_tailoring(
                build_refinement_prompt(request, initial),
                0.05,
            )
        )
    except (OpenAIError, AiOutputError):
        logger.warning(
            "ATS refinement failed; returning the valid initial result.",
            exc_info=True,
        )
        return protect_original_score(initial)

    if not same_keyword_classification(initial, candidate):
        return protect_original_score(initial)

    initial_coverage = keyword_coverage(
        initial_document,
        initial.matched_keywords,
    )
    candidate_coverage = keyword_coverage(
        candidate_document,
        candidate.matched_keywords,
    )
    initial_placement = keyword_placement_score(
        initial_document,
        initial.matched_keywords,
    )
    candidate_placement = keyword_placement_score(
        candidate_document,
        candidate.matched_keywords,
    )

    if (
        candidate.ats_match_score > initial.ats_match_score
        and (candidate_coverage, candidate_placement)
        > (initial_coverage, initial_placement)
    ):
        return protect_original_score(candidate)

    return protect_original_score(initial)


def render_cv_html(document: TailoredCvDocument) -> str:
    """Render an auto-escaped HTML document suitable for browser or PDF output."""

    language_sample = " ".join(
        part
        for part in [document.headline, document.professional_summary]
        if part
    ).casefold()
    norwegian_markers = {
        " og ",
        " med ",
        " erfaring ",
        " utdanning ",
        " ferdigheter ",
        " prosjekt ",
        " ansvar ",
    }
    is_norwegian = any(character in language_sample for character in "æøå") or any(
        marker in f" {language_sample} " for marker in norwegian_markers
    )
    labels = (
        {
            "lang": "no",
            "summary": "Profil",
            "skills": "Ferdigheter",
            "experience": "Erfaring",
            "projects": "Utvalgte prosjekter",
            "education": "Utdanning",
            "certifications": "Sertifikater",
            "courses": "Kurs og opplæring",
            "languages": "Språk",
        }
        if is_norwegian
        else {
            "lang": "en",
            "summary": "Professional summary",
            "skills": "Core skills",
            "experience": "Professional experience",
            "projects": "Selected projects",
            "education": "Education",
            "certifications": "Certifications",
            "courses": "Courses and training",
            "languages": "Languages",
        }
    )
    return cv_template.render(
        cv=document.model_dump(mode="json"),
        labels=labels,
    )


def render_pdf(document: TailoredCvDocument) -> bytes:
    """Compile the rendered HTML to a PDF byte string with WeasyPrint."""

    html = render_cv_html(document)
    pdf = HTML(string=html).write_pdf()

    if not pdf:
        raise RuntimeError("WeasyPrint returned an empty PDF.")

    return pdf


