def create_openai_client(settings: Settings) -> AsyncOpenAI:
    """Create the process-wide asynchronous OpenAI client."""

    return AsyncOpenAI(
        api_key=settings.openai_api_key.get_secret_value(),
        timeout=settings.openai_timeout_seconds,
        max_retries=settings.openai_max_retries,
    )


@asynccontextmanager
async def lifespan(application: FastAPI) -> AsyncIterator[None]:
    """Initialize and cleanly close shared network resources."""

    settings = get_settings()
    openai_client = create_openai_client(settings)
    scraping_client = httpx.AsyncClient(
        follow_redirects=False,
        timeout=httpx.Timeout(settings.scraping_timeout_seconds),
        headers={
            "User-Agent": SCRAPER_USER_AGENT,
            "Accept": "text/html,application/xhtml+xml",
            "Accept-Language": "nb-NO,nb;q=0.9,en;q=0.8",
        },
    )
    application.state.openai_client = openai_client
    application.state.scraping_client = scraping_client

    try:
        yield
    finally:
        await scraping_client.aclose()
        await openai_client.close()


