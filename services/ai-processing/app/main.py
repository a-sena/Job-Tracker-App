def document_evidence_fragments(
    document: TailoredCvDocument,
) -> list[tuple[str, str]]:
    """Return searchable factual fragments with user-facing section labels."""

    fragments: list[tuple[str, str]] = []

    def add(section: str, *values: str | None) -> None:
        fragments.extend(
            (section, value.strip())
            for value in values
            if value and value.strip()
        )

    add("Profile", document.headline, document.professional_summary)
    add("Skills", *document.skills)
    for experience in document.work_experience:
        add(
            "Work experience",
            experience.job_title,
            experience.company,
            experience.location,
            *experience.bullet_points,
        )
    for project in document.projects:
        add(
            "Projects",
            project.name,
            project.role,
            *project.technologies,
            *project.bullet_points,
        )
    for education in document.education:
        add(
            "Education",
            education.qualification,
            education.institution,
            education.start_date,
            education.end_date,
            *education.details,
        )
    add("Certifications", *document.certifications)
    for course in document.courses:
        add(
            "Courses",
            course.name,
            course.provider,
            course.completed_date,
            *course.details,
        )
    add("Languages", *document.languages)
    return fragments


def document_evidence_text(document: TailoredCvDocument) -> str:
    """Flatten factual ATS sections while preserving their source boundaries."""

    return " ".join(text for _, text in document_evidence_fragments(document))


def calculate_ats_score_breakdown(
    document: TailoredCvDocument,
    matched_keywords: list[str],
    missing_keywords: list[str],
) -> list[AtsScoreComponent]:
    """Calculate transparent 60/20/10/10 components without model grading."""

    total_keywords = len(matched_keywords) + len(missing_keywords)
    if total_keywords == 0:
        coverage_points = 0.0
    else:
        coverage_points = 60 * len(matched_keywords) / total_keywords

    headline_summary = " ".join(
        part for part in [document.headline, document.professional_summary] if part
    )
    skills_text = " ".join(document.skills)
    evidence_text = document_evidence_text(document)

    if matched_keywords:
        placement_total = 0.0
        aligned = 0
        for keyword in matched_keywords:
            in_summary = _keyword_present(keyword, headline_summary)
            placement_total += 0.35 if in_summary else 0
            placement_total += 0.25 if _keyword_present(keyword, skills_text) else 0
            placement_total += 0.40 if _keyword_present(keyword, evidence_text) else 0
            aligned += int(in_summary)
        placement_points = 20 * placement_total / len(matched_keywords)
        alignment_points = 10 * min(
            1.0,
            aligned / max(1, min(3, len(matched_keywords))),
        )
    else:
        placement_points = 0.0
        alignment_points = 0.0

    readability_points = 2.0 if document.full_name.strip() else 0.0
    summary_length = len(document.professional_summary.strip())
    readability_points += 2.0 if 60 <= summary_length <= 900 else 1.0
    has_evidence_section = bool(
        document.work_experience
        or document.projects
        or document.education
        or document.courses
    )
    readability_points += 2.0 if has_evidence_section else 0.0
    bullets = [
        *[
            bullet
            for experience in document.work_experience
            for bullet in experience.bullet_points
        ],
        *[
            bullet for project in document.projects for bullet in project.bullet_points
        ],
    ]
    if not bullets or all(20 <= len(bullet.strip()) <= 350 for bullet in bullets):
        readability_points += 2.0
    readability_points += 2.0 if document.skills else 1.0

    return [
        AtsScoreComponent(
            key="keywordCoverage",
            label="Supported keyword coverage",
            score=round(coverage_points, 2),
            maxScore=60,
            explanation=(
                f"{len(matched_keywords)} of {total_keywords} assessed requirements "
                "are supported by the CV."
                if total_keywords
                else "No high-signal requirements were available to assess."
            ),
        ),
        AtsScoreComponent(
            key="keywordPlacement",
            label="Keyword placement",
            score=round(placement_points, 2),
            maxScore=20,
            explanation=(
                "Measures truthful placement across the profile, skills, and "
                "evidence sections."
            ),
        ),
        AtsScoreComponent(
            key="roleAlignment",
            label="Role alignment",
            score=round(alignment_points, 2),
            maxScore=10,
            explanation=(
                "Measures whether supported role requirements are visible early "
                "in the headline or summary."
            ),
        ),
        AtsScoreComponent(
            key="readability",
            label="ATS readability",
            score=round(readability_points, 2),
            maxScore=10,
            explanation=(
                "Checks summary length, factual sections, skills, and readable "
                "bullet structure."
            ),
        ),
    ]


def calculate_ats_score(
    document: TailoredCvDocument,
    matched_keywords: list[str],
    missing_keywords: list[str],
) -> int:
    """Return the rounded total of the deterministic ATS score components."""

    components = calculate_ats_score_breakdown(
        document,
        matched_keywords,
        missing_keywords,
    )
    return max(0, min(100, round(sum(item.score for item in components))))


def build_verified_keyword_evidence(
    master_cv: MasterCv,
    matched_keywords: list[str],
    model_evidence: list[KeywordEvidence],
) -> list[AtsKeywordEvidenceDetail]:
    """Attach each matched term to a grounded CV fragment when available."""

    document = source_cv_document(master_cv)
    fragments = document_evidence_fragments(document)
    source_text = _master_cv_source_text(master_cv)
    model_by_keyword: dict[str, list[str]] = {}
    for item in model_evidence:
        if _search_normalize(item.evidence_text) in _search_normalize(source_text):
            model_by_keyword.setdefault(normalize_keyword(item.keyword), []).append(
                item.evidence_text
            )

    details: list[AtsKeywordEvidenceDetail] = []
    for keyword in matched_keywords:
        direct = next(
            (
                (section, text)
                for section, text in fragments
                if _keyword_present(keyword, text)
            ),
            None,
        )
        if direct is not None:
            details.append(
                AtsKeywordEvidenceDetail(
                    keyword=keyword,
                    section=direct[0],
                    evidenceText=direct[1],
                )
            )
            continue

        grounded_excerpt = next(
            iter(model_by_keyword.get(normalize_keyword(keyword), [])),
            None,
        )
        if grounded_excerpt:
            section = next(
                (
                    fragment_section
                    for fragment_section, fragment_text in fragments
                    if _search_normalize(grounded_excerpt)
                    in _search_normalize(fragment_text)
                ),
                "CV evidence",
            )
            details.append(
                AtsKeywordEvidenceDetail(
                    keyword=keyword,
                    section=section,
                    evidenceText=grounded_excerpt,
                )
            )
    return details


def build_section_feedback(
    document: TailoredCvDocument,
    matched_keywords: list[str],
) -> list[AtsSectionFeedback]:
    """Generate deterministic section-level findings and safe recommendations."""

    total_matched = len(matched_keywords)

    def match_count(text: str) -> int:
        return sum(
            1 for keyword in matched_keywords if _keyword_present(keyword, text)
        )

    profile_text = " ".join(
        value
        for value in [document.headline, document.professional_summary]
        if value
    )
    profile_matches = match_count(profile_text)
    summary_length = len(document.professional_summary.strip())
    profile_strong = (
        60 <= summary_length <= 900
        and (not total_matched or profile_matches >= min(3, total_matched))
    )

    skills_text = " ".join(document.skills)
    skills_matches = match_count(skills_text)
    evidence_text = " ".join(
        text
        for section, text in document_evidence_fragments(document)
        if section in {"Work experience", "Projects"}
    )
    evidence_matches = match_count(evidence_text)
    has_experience_evidence = bool(document.work_experience or document.projects)

    credentials_text = " ".join(
        text
        for section, text in document_evidence_fragments(document)
        if section
        in {"Education", "Certifications", "Courses", "Languages"}
    )
    credential_matches = match_count(credentials_text)
    has_credentials = bool(
        document.education
        or document.certifications
        or document.courses
        or document.languages
    )

    return [
        AtsSectionFeedback(
            section="Profile and summary",
            status="strong" if profile_strong else "needs_attention",
            findings=[
                f"{profile_matches} of {total_matched} supported requirements are "
                "visible in the headline or summary.",
                f"The professional summary contains {summary_length} characters.",
            ],
            recommendations=(
                []
                if profile_strong
                else [
                    "Bring the most important supported role terms into the opening "
                    "lines without adding unsupported claims."
                ]
            ),
        ),
        AtsSectionFeedback(
            section="Skills",
            status=(
                "strong"
                if document.skills and (not total_matched or skills_matches > 0)
                else "needs_attention" if document.skills else "not_available"
            ),
            findings=[
                f"The CV lists {len(document.skills)} skills; {skills_matches} "
                "supported requirements appear there."
            ],
            recommendations=(
                []
                if skills_matches > 0
                else [
                    "Add only already-demonstrated job-relevant skills to the skills "
                    "section, using the vacancy's terminology when equivalent."
                ]
            ),
        ),
        AtsSectionFeedback(
            section="Experience and projects",
            status=(
                "strong"
                if has_experience_evidence and evidence_matches > 0
                else "needs_attention"
                if has_experience_evidence
                else "not_available"
            ),
            findings=[
                f"{len(document.work_experience)} work entries and "
                f"{len(document.projects)} projects provide {evidence_matches} "
                "supported requirement matches."
            ],
            recommendations=(
                []
                if evidence_matches > 0
                else [
                    "Connect supported skills to concrete existing work or project "
                    "bullets; do not create new experience."
                ]
            ),
        ),
        AtsSectionFeedback(
            section="Education and credentials",
            status=(
                "strong"
                if has_credentials and credential_matches > 0
                else "needs_attention" if has_credentials else "not_available"
            ),
            findings=[
                f"Education, certifications, courses, and languages support "
                f"{credential_matches} assessed requirements."
            ],
            recommendations=(
                []
                if has_credentials
                else [
                    "Add factual education, certifications, courses, or languages "
                    "when they are relevant and verifiable."
                ]
            ),
        ),
    ]


def classify_job_requirement(keyword: str, job_description: str) -> str:
    """Classify requirement strength from nearby, explicit vacancy wording."""

    normalized_description = _search_normalize(job_description)
    normalized_keyword = _search_normalize(keyword)
    index = normalized_description.find(normalized_keyword)
    if index < 0:
        return "general"

    context = normalized_description[max(0, index - 100) : index + len(keyword) + 100]
    required_markers = (
        "must",
        "required",
        "requirement",
        "requirements",
        "må ",
        "skal ",
        "krav",
        "obligatorisk",
    )
    preferred_markers = (
        "preferred",
        "nice to have",
        "advantage",
        "desirable",
        "ønskelig",
        "en fordel",
        "gjerne",
    )
    if any(marker in context for marker in required_markers):
        return "required"
    if any(marker in context for marker in preferred_markers):
        return "preferred"
    return "general"


def build_requirement_details(
    job_description: str,
    matched_keywords: list[str],
    missing_keywords: list[str],
    evidence: list[AtsKeywordEvidenceDetail],
) -> list[AtsRequirementDetail]:
    evidence_by_keyword = {
        normalize_keyword(item.keyword): item for item in evidence
    }
    details: list[AtsRequirementDetail] = []
    for keyword, requirement_status in [
        *((value, "matched") for value in matched_keywords),
        *((value, "unsupported") for value in missing_keywords),
    ]:
        item = evidence_by_keyword.get(normalize_keyword(keyword))
        details.append(
            AtsRequirementDetail(
                keyword=keyword,
                category=classify_job_requirement(keyword, job_description),
                status=requirement_status,
                section=item.section if item else None,
                evidenceText=item.evidence_text if item else None,
            )
        )
    category_order = {"required": 0, "preferred": 1, "general": 2}
    status_order = {"unsupported": 0, "matched": 1}
    return sorted(
        details,
        key=lambda item: (
            category_order[item.category],
            status_order[item.status],
            item.keyword.casefold(),
        ),
    )


def build_review_confidence(
    reviewed_count: int,
    matched_count: int,
    evidence_count: int,
) -> tuple[str, str]:
    evidence_ratio = evidence_count / matched_count if matched_count else 1.0
    if reviewed_count >= 8 and evidence_ratio >= 0.8:
        return (
            "high",
            "The review assessed a broad requirement set and most positive matches have verified CV evidence.",
        )
    if reviewed_count >= 5 and evidence_ratio >= 0.5:
        return (
            "medium",
            "The review has a usable requirement set, but some matches or vacancy wording remain less explicit.",
        )
    return (
        "low",
        "The vacancy or CV supplied too little explicit evidence for a highly confident comparison.",
    )


def build_ats_review_details(
    master_cv: MasterCv,
    job_description: str,
    matched_keywords: list[str],
    missing_keywords: list[str],
    model_evidence: list[KeywordEvidence],
) -> AtsReviewDetails:
    """Build explainable review details exclusively from grounded CV data."""

    document = source_cv_document(master_cv)
    evidence = build_verified_keyword_evidence(
        master_cv,
        matched_keywords,
        model_evidence,
    )
    strengths = [
        f"{item.keyword} is supported in {item.section}: {item.evidence_text}"
        for item in evidence[:4]
    ]
    if not strengths:
        strengths = [
            "No high-signal vacancy requirement had a displayable evidence excerpt."
        ]

    priority_actions = [
        (
            f"Keep {keyword} marked as unsupported unless you can add genuine "
            "evidence from your existing experience, projects, education, or courses."
        )
        for keyword in missing_keywords[:4]
    ]
    profile_text = " ".join(
        value
        for value in [document.headline, document.professional_summary]
        if value
    )
    if matched_keywords and not all(
        _keyword_present(keyword, profile_text) for keyword in matched_keywords[:3]
    ):
        priority_actions.insert(
            0,
            "Surface the most important supported requirements earlier in the "
            "professional summary.",
        )

    confidence, confidence_explanation = build_review_confidence(
        len(matched_keywords) + len(missing_keywords),
        len(matched_keywords),
        len(evidence),
    )
    return AtsReviewDetails(
        scoreBreakdown=calculate_ats_score_breakdown(
            document,
            matched_keywords,
            missing_keywords,
        ),
        keywordEvidence=evidence,
        strengths=strengths,
        priorityActions=priority_actions[:6],
        sectionFeedback=build_section_feedback(document, matched_keywords),
        requirements=build_requirement_details(
            job_description,
            matched_keywords,
            missing_keywords,
            evidence,
        ),
        confidence=confidence,
        confidenceExplanation=confidence_explanation,
    )


def validate_keyword_partition(
    review: AtsReviewCandidate,
) -> AtsReviewCandidate:
    """Reject contradictory classifications rather than silently trusting them."""

    matched = {
        normalize_keyword(keyword) for keyword in review.matched_keywords
    }
    missing = {
        normalize_keyword(keyword) for keyword in review.missing_keywords
    }
    if matched & missing:
        raise AiOutputError(
            "OpenAI classified the same ATS keyword as both matched and missing."
        )

    if not matched and not missing:
        raise AiOutputError("OpenAI returned no high-signal ATS keywords.")

    return review


async def review_cv_with_openai(
    request: GenerateTailoredCvRequest,
    client: AsyncOpenAI,
    settings: Settings,
) -> AtsReview:
    """Assess an unmodified CV with the same rubric used by tailoring."""

    completion = await client.chat.completions.create(
        model=settings.openai_model,
        messages=[
            {"role": "system", "content": ATS_REVIEW_SYSTEM_PROMPT},
            {"role": "user", "content": build_ats_review_prompt(request)},
        ],
        response_format={"type": "json_object"},
        temperature=0,
        max_tokens=settings.openai_max_output_tokens,
    )

    if not completion.choices:
        raise AiOutputError("OpenAI returned no ATS review choices.")

    choice = completion.choices[0]
    if getattr(choice.message, "refusal", None):
        raise AiOutputError("OpenAI refused the ATS review request.")

    if choice.finish_reason != "stop":
        raise AiOutputError(
            f"OpenAI ATS review ended with finish reason '{choice.finish_reason}'."
        )

    content = choice.message.content
    if not content:
        raise AiOutputError("OpenAI returned an empty ATS review.")

    try:
        review = AtsReviewCandidate.model_validate_json(content)
    except ValidationError as exc:
        raise AiOutputError(
            "OpenAI returned JSON that does not match the ATS review contract."
        ) from exc

    validated = validate_keyword_partition(review)
    matched, missing = reconcile_keyword_evidence(
        request.master_cv,
        validated.matched_keywords,
        validated.missing_keywords,
        validated.keyword_evidence,
    )
    return AtsReview(
        atsMatchScore=calculate_ats_score(
            source_cv_document(request.master_cv),
            matched,
            missing,
        ),
        matchedKeywords=matched,
        missingKeywords=missing,
        explanation=validated.explanation,
        details=build_ats_review_details(
            request.master_cv,
            request.job_description,
            matched,
            missing,
            validated.keyword_evidence,
        ),
    )


