MAX_SCRAPER_REDIRECTS = 4


async def validate_public_job_url(url: str) -> str:
    """
    Reject local, private, link-local, and non-HTTP destinations before fetching.

    Production deployments should enforce the same restriction at the network
    egress layer to protect against DNS rebinding.
    """

    parsed = urlparse(url.strip())
    if parsed.scheme not in {"http", "https"} or not parsed.hostname:
        raise JobExtractionError(
            "The job URL must be an absolute HTTP or HTTPS URL.",
            status_code=400,
        )

    if parsed.username or parsed.password:
        raise JobExtractionError(
            "Job URLs containing credentials are not allowed.",
            status_code=400,
        )

    try:
        port = parsed.port
    except ValueError as exc:
        raise JobExtractionError("The job URL contains an invalid port.", 400) from exc

    if port is not None and port not in {80, 443}:
        raise JobExtractionError(
            "Only standard HTTP and HTTPS ports are allowed.",
            status_code=400,
        )

    try:
        address_info = await run_in_threadpool(
            socket.getaddrinfo,
            parsed.hostname,
            port or (443 if parsed.scheme == "https" else 80),
            socket.AF_UNSPEC,
            socket.SOCK_STREAM,
        )
    except socket.gaierror as exc:
        raise JobExtractionError(
            "The job posting hostname could not be resolved.",
            status_code=400,
        ) from exc

    addresses = {item[4][0].split("%", maxsplit=1)[0] for item in address_info}
    if not addresses:
        raise JobExtractionError(
            "The job posting hostname returned no network address.",
            status_code=400,
        )

    for address in addresses:
        try:
            if not ipaddress.ip_address(address).is_global:
                raise JobExtractionError(
                    "Private or local network addresses are not allowed.",
                    status_code=400,
                )
        except ValueError as exc:
            raise JobExtractionError(
                "The job posting hostname returned an invalid network address.",
                status_code=400,
            ) from exc

    return parsed._replace(fragment="").geturl()


async def fetch_job_page(
    job_url: str,
    client: httpx.AsyncClient,
    max_response_bytes: int,
) -> tuple[str, str]:
    """Fetch a bounded HTML document and validate every redirect destination."""

    current_url = job_url

    for redirect_count in range(MAX_SCRAPER_REDIRECTS + 1):
        current_url = await validate_public_job_url(current_url)

        try:
            async with client.stream("GET", current_url) as response:
                if response.is_redirect:
                    location = response.headers.get("location")
                    if not location:
                        raise JobExtractionError(
                            "The job site returned an invalid redirect."
                        )
                    if redirect_count >= MAX_SCRAPER_REDIRECTS:
                        raise JobExtractionError(
                            "The job site redirected too many times."
                        )
                    current_url = urljoin(current_url, location)
                    continue

                response.raise_for_status()
                content_type = response.headers.get("content-type", "").lower()
                if not (
                    content_type.startswith("text/html")
                    or content_type.startswith("application/xhtml+xml")
                ):
                    raise JobExtractionError(
                        "The URL did not return an HTML job posting.",
                        status_code=415,
                    )

                chunks: list[bytes] = []
                total_bytes = 0
                async for chunk in response.aiter_bytes():
                    total_bytes += len(chunk)
                    if total_bytes > max_response_bytes:
                        raise JobExtractionError(
                            "The job page is too large to process.",
                            status_code=413,
                        )
                    chunks.append(chunk)

                encoding = response.encoding or "utf-8"
                return str(response.url), b"".join(chunks).decode(
                    encoding,
                    errors="replace",
                )
        except httpx.TimeoutException as exc:
            raise JobExtractionError(
                "The job site did not respond in time.",
                status_code=504,
            ) from exc
        except httpx.HTTPStatusError as exc:
            raise JobExtractionError(
                f"The job site returned HTTP {exc.response.status_code}.",
                status_code=502,
            ) from exc
        except httpx.RequestError as exc:
            raise JobExtractionError(
                "The job site could not be reached.",
                status_code=502,
            ) from exc

    raise JobExtractionError("The job site redirected too many times.")


def clean_text(value: object | None) -> str:
    if value is None:
        return ""
    return re.sub(r"\s+", " ", str(value)).strip()


def clean_html_description(value: object | None) -> str:
    if value is None:
        return ""

    soup = BeautifulSoup(str(value), "html.parser")
    lines = [
        clean_text(line)
        for line in soup.get_text("\n", strip=True).splitlines()
        if clean_text(line)
    ]

    deduplicated: list[str] = []
    for line in lines:
        if not deduplicated or deduplicated[-1] != line:
            deduplicated.append(line)

    return "\n\n".join(deduplicated)[:50_000]


def iter_json_ld_nodes(value: object) -> list[dict[str, object]]:
    nodes: list[dict[str, object]] = []

    if isinstance(value, list):
        for item in value:
            nodes.extend(iter_json_ld_nodes(item))
    elif isinstance(value, dict):
        nodes.append(value)
        graph = value.get("@graph")
        if graph is not None:
            nodes.extend(iter_json_ld_nodes(graph))

    return nodes


def is_job_posting_node(node: dict[str, object]) -> bool:
    node_type = node.get("@type")
    if isinstance(node_type, str):
        return node_type.casefold() == "jobposting"
    if isinstance(node_type, list):
        return any(
            isinstance(value, str) and value.casefold() == "jobposting"
            for value in node_type
        )
    return False


def json_ld_company(node: dict[str, object]) -> str:
    organization = node.get("hiringOrganization")
    if isinstance(organization, dict):
        return clean_text(organization.get("name"))
    return clean_text(organization)


def json_ld_location(node: dict[str, object]) -> str:
    if clean_text(node.get("jobLocationType")).casefold() == "telecommute":
        return "Remote"

    locations = node.get("jobLocation")
    if not isinstance(locations, list):
        locations = [locations]

    formatted_locations: list[str] = []
    for location in locations:
        if not isinstance(location, dict):
            continue

        address = location.get("address")
        if not isinstance(address, dict):
            text = clean_text(address)
            if text:
                formatted_locations.append(text)
            continue

        parts = [
            clean_text(address.get("addressLocality")),
            clean_text(address.get("addressRegion")),
            clean_text(address.get("addressCountry")),
        ]
        formatted = ", ".join(part for part in parts if part)
        if formatted:
            formatted_locations.append(formatted)

    return " / ".join(dict.fromkeys(formatted_locations))


def meta_content(
    soup: BeautifulSoup,
    *,
    property_name: str | None = None,
    name: str | None = None,
) -> str:
    selector = (
        f'meta[property="{property_name}"]'
        if property_name
        else f'meta[name="{name}"]'
    )
    element = soup.select_one(selector)
    return clean_text(element.get("content")) if element else ""


def selected_text(soup: BeautifulSoup, selectors: list[str]) -> str:
    for selector in selectors:
        element = soup.select_one(selector)
        if element:
            text = clean_text(element.get_text(" ", strip=True))
            if text:
                return text
    return ""


def selected_description(soup: BeautifulSoup, selectors: list[str]) -> str:
    for selector in selectors:
        element = soup.select_one(selector)
        if element:
            description = clean_html_description(str(element))
            if description:
                return description
    return ""


def extract_job_details(job_url: str, html: str) -> ExtractedJob:
    """Extract schema.org JobPosting data first, then conservative HTML fallbacks."""

    soup = BeautifulSoup(html, "html.parser")
    job_node: dict[str, object] | None = None

    for script in soup.select('script[type="application/ld+json"]'):
        raw_json = script.string or script.get_text()
        if not raw_json.strip():
            continue

        try:
            parsed_json = json.loads(raw_json)
        except (json.JSONDecodeError, TypeError):
            continue

        job_node = next(
            (
                node
                for node in iter_json_ld_nodes(parsed_json)
                if is_job_posting_node(node)
            ),
            None,
        )
        if job_node:
            break

    title = clean_text(job_node.get("title")) if job_node else ""
    company = json_ld_company(job_node) if job_node else ""
    description = (
        clean_html_description(job_node.get("description")) if job_node else ""
    )
    location = json_ld_location(job_node) if job_node else ""

    title = title or meta_content(soup, property_name="og:title")
    title = title or selected_text(soup, ["h1", "[itemprop='title']"])
    title = title or clean_text(soup.title.string if soup.title else "")

    company = company or selected_text(
        soup,
        [
            "[itemprop='hiringOrganization']",
            "[data-testid*='company']",
            ".company",
            ".company-name",
        ],
    )
    company = company or meta_content(soup, property_name="og:site_name")
    company = company or meta_content(soup, name="author")

    location = location or selected_text(
        soup,
        [
            "[itemprop='jobLocation']",
            "[data-testid*='location']",
            ".job-location",
            ".location",
        ],
    )

    description = description or selected_description(
        soup,
        [
            "[itemprop='description']",
            "[data-testid*='description']",
            ".job-description",
            "#job-description",
            "main article",
            "article",
            "main",
        ],
    )
    description = description or meta_content(soup, property_name="og:description")
    description = description or meta_content(soup, name="description")

    warnings: list[str] = []
    if not title:
        warnings.append("Job title could not be extracted; enter it manually.")
    if not company:
        warnings.append("Company could not be extracted; enter it manually.")
    if not description:
        warnings.append("Job description could not be extracted; enter it manually.")
    if not location:
        warnings.append("Location could not be extracted.")

    return ExtractedJob(
        jobUrl=job_url,
        title=title[:300],
        company=company[:200],
        description=description[:50_000],
        location=location[:200] or None,
        warnings=warnings,
    )


