def reconcile_keyword_evidence(
    master_cv: MasterCv,
    matched_keywords: list[str],
    missing_keywords: list[str],
    evidence: list[KeywordEvidence],
) -> tuple[list[str], list[str]]:
    """Keep a match only when the source CV or a grounded excerpt supports it."""

    source_text = _master_cv_source_text(master_cv)
    evidence_by_keyword: dict[str, list[str]] = {}
    for item in evidence:
        evidence_by_keyword.setdefault(normalize_keyword(item.keyword), []).append(
            item.evidence_text
        )

    verified: list[str] = []
    rejected: list[str] = []
    for keyword in matched_keywords:
        direct_support = _keyword_present(keyword, source_text)
        grounded_excerpt = any(
            _search_normalize(excerpt) in _search_normalize(source_text)
            for excerpt in evidence_by_keyword.get(normalize_keyword(keyword), [])
        )
        (verified if direct_support or grounded_excerpt else rejected).append(keyword)

    verified_keys = {normalize_keyword(keyword) for keyword in verified}
    unsupported_missing: list[str] = []
    for keyword in missing_keywords:
        key = normalize_keyword(keyword)
        if _keyword_present(keyword, source_text):
            if key not in verified_keys:
                verified.append(keyword)
                verified_keys.add(key)
        else:
            unsupported_missing.append(keyword)

    combined_missing = [*unsupported_missing, *rejected]
    unique_missing: list[str] = []
    seen_missing: set[str] = set()
    for keyword in combined_missing:
        key = normalize_keyword(keyword)
        if key and key not in seen_missing and key not in verified_keys:
            unique_missing.append(keyword)
            seen_missing.add(key)

    return verified, unique_missing


