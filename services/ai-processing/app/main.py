    missing_keywords: list[str] = Field(default_factory=list, max_length=100)
    ats_match_score: int = Field(ge=0, le=100)

    @field_validator("matched_keywords", "missing_keywords")
    @classmethod
    def normalize_keywords(cls, values: list[str]) -> list[str]:
        normalized: list[str] = []
        seen: set[str] = set()

        for value in values:
            keyword = value.strip()
            key = keyword.casefold()
            if keyword and key not in seen:
                normalized.append(keyword)
                seen.add(key)

        return normalized


